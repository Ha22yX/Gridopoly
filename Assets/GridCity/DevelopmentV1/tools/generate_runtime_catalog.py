"""Generate the small firmware lookup/CRC table; no artwork is embedded."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parents[2]
OUTPUT = REPO / "Firmware/libraries/GridopolyCore/src/gridopoly/assets/DevelopmentArtworkCatalog.h"


def render():
    manifest = json.loads((ROOT / "manifests/development-v1.json").read_text(encoding="utf-8"))
    records = {(r["key"], r["level"]): r for r in manifest["assets"]}
    keys = sorted({r["key"] for r in manifest["assets"]})
    assert len(keys) == 22 and len(records) == 132
    rows = []
    for key in keys:
        checksums = {}
        for target, size in [("tile_rgb565", 51200), ("player_rgb565", 32768)]:
            values = []
            for level in range(1, 6):
                item = records[key, level]["files"][target]
                data = (ROOT / item["path"]).read_bytes()
                assert len(data) == size == item["bytes"]
                assert hashlib.sha256(data).hexdigest() == item["sha256"]
                values.append(f"0x{zlib.crc32(data):08X}u")
            checksums[target] = "{" + ", ".join(values) + "}"
        png_sizes, png_crcs = [], []
        for level in range(1, 6):
            item = records[key, level]["files"]["tile_png"]
            data = (ROOT / item["path"]).read_bytes()
            assert len(data) == item["bytes"]
            assert hashlib.sha256(data).hexdigest() == item["sha256"]
            png_sizes.append(str(len(data)) + "u")
            png_crcs.append(f"0x{zlib.crc32(data):08X}u")
        sizes = "{" + ", ".join(png_sizes) + "}"
        crcs = "{" + ", ".join(png_crcs) + "}"
        tile_id = records[key, 0]["tile_id"]
        rows.append(f'    {{"{key}", "{tile_id}", {checksums["tile_rgb565"]}, {checksums["player_rgb565"]}, {sizes}, {crcs}}},')
    return '''// Generated by Assets/GridCity/DevelopmentV1/tools/generate_runtime_catalog.py.
// v1 is immutable: publish changed artwork under a new versioned URL.
#pragma once
#include <cstddef>
#include <cstdint>
#include <cstring>

namespace gridopoly { namespace assets {

static constexpr char kDevelopmentAssetPrefix[] = "/assets/development/v1/";
static constexpr char kDevelopmentCatalogVersion[] = "v1";
static constexpr std::size_t kDevelopmentPropertyCount = 22;
static constexpr std::size_t kTileDevelopmentImageBytes = 160u * 160u * 2u;
static constexpr std::size_t kPlayerDevelopmentImageBytes = 128u * 128u * 2u;

enum class DevelopmentTarget : std::uint8_t { Tile, Player };
struct DevelopmentProperty {
  const char* key;
  const char* tileId;
  std::uint32_t tileCrc32[5];
  std::uint32_t playerCrc32[5];
  std::uint32_t webPngBytes[5];
  std::uint32_t webPngCrc32[5];
};
static constexpr DevelopmentProperty kDevelopmentProperties[] = {
''' + "\n".join(rows) + '''
};
static_assert(sizeof(kDevelopmentProperties) / sizeof(kDevelopmentProperties[0]) ==
              kDevelopmentPropertyCount, "Every buildable property needs development artwork");

inline bool validDevelopmentLevel(std::uint8_t level) { return level >= 1 && level <= 5; }
inline const DevelopmentProperty* developmentProperty(const char* key) {
  if (!key) return nullptr;
  for (const auto& property : kDevelopmentProperties)
    if (std::strcmp(property.key, key) == 0) return &property;
  return nullptr;
}
inline const DevelopmentProperty* developmentPropertyForTileId(const char* tileId) {
  if (!tileId) return nullptr;
  for (const auto& property : kDevelopmentProperties)
    if (std::strcmp(property.tileId, tileId) == 0) return &property;
  return nullptr;
}
// Zero denotes an invalid key/level. Validate those before starting a request.
inline std::uint32_t developmentCrc32(const DevelopmentProperty* property,
                                    std::uint8_t level, DevelopmentTarget target) {
  if (!property || !validDevelopmentLevel(level)) return 0;
  return target == DevelopmentTarget::Tile ? property->tileCrc32[level - 1]
                                           : property->playerCrc32[level - 1];
}

} }  // namespace gridopoly::assets
'''


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render().encode("utf-8")
    if args.check:
        assert OUTPUT.read_bytes().replace(b"\r\n", b"\n") == expected, "Runtime catalog is stale"
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_bytes(expected)
    print("GRIDOPOLY_DEVELOPMENT_CATALOG_PASS properties=22 states=110 crc_values=330")


if __name__ == "__main__":
    main()
