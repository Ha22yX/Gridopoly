"""Freeze CRCs for the unchanged /assets/tiles source without rewriting pixels."""
import argparse
import json
from pathlib import Path
import zlib

root = Path(__file__).resolve().parents[3]
manifest = root / 'Firmware/PlayerConsole/src/assets/grid_city_tile_assets.manifest.json'
target = manifest.with_name('legacy_tile_checksums.h')
rows = []
for asset in json.loads(manifest.read_text(encoding='utf-8'))['assets']:
    key = asset['key']
    data = (root / 'Assets/GridCity/StreetV3/device-rgb565' / (key + '.rgb565')).read_bytes()
    assert len(data) == 32768, key
    rows.append(f'    {{"{key}", 0x{zlib.crc32(data):08X}u}},')
source = '''// Generated by tools/generate-legacy-artwork-checksums.py; no pixel arrays.
#pragma once
#include <cstdint>
#include <cstring>
struct LegacyTileChecksum { const char *key; std::uint32_t crc; };
static constexpr LegacyTileChecksum kLegacyTileChecksums[] = {
''' + '\n'.join(rows) + '''
};
inline const LegacyTileChecksum *legacyTileChecksum(const char *key) {
    if (key) for (const auto &item : kLegacyTileChecksums)
        if (std::strcmp(item.key, key) == 0) return &item;
    return nullptr;
}
'''
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    assert target.read_text(encoding='utf-8') == source, 'Legacy CRC catalog is stale'
else:
    target.write_bytes(source.encode('utf-8'))
print(f'Legacy tile CRC catalog: {len(rows)} files verified')
