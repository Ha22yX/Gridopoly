import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';

const sourceUrl = new URL('../src/WebUi.h', import.meta.url);
const outputUrl = new URL('../src/WebUiGzip.h', import.meta.url);
const projectUrl = new URL('../../../', import.meta.url);
const tileAssetUrl = new URL('Assets/GridCity/StreetV3/device/', projectUrl);
const manifestUrl = new URL(
  'Assets/GridCity/StreetV3/manifests/grid-city-street-assets-v3.json', projectUrl);
const source = fs.readFileSync(sourceUrl, 'utf8');
const manifest = JSON.parse(fs.readFileSync(manifestUrl, 'utf8'));
const match = source.match(/R"GRIDOPOLY_HTML\(([\s\S]*?)\)GRIDOPOLY_HTML";/);
if (!match) throw new Error('WebUi.h raw HTML literal was not found');

const html = Buffer.from(match[1], 'utf8');
const tileAssetNames = [...new Set(Array.from(match[1].matchAll(/['"]([a-z0-9-]+\.png)['"]/g),
  value => value[1]))];
const manifestAssets = manifest.assets ?? [];
const expectedNames = manifestAssets.map(asset => `${asset.key}.png`).sort();
if (manifestAssets.length !== 36 || tileAssetNames.length !== 36) {
  throw new Error(`expected 36 Street V3 web tile assets, found ${tileAssetNames.length}`);
}
if (JSON.stringify(tileAssetNames.slice().sort()) !== JSON.stringify(expectedNames)) {
  throw new Error('web UI PNG references do not exactly match the Street V3 manifest');
}
for (const asset of manifestAssets) {
  const name = `${asset.key}.png`;
  const truth = asset.source ? new URL(asset.source, projectUrl) : new URL(name, tileAssetUrl);
  if (!fs.existsSync(truth)) throw new Error(`missing Street V3 tile asset truth: ${name}`);
}
const compressed = gzipSync(html, { level: 9, mtime: 0 });
const etagToken = `gridopoly-ui-${createHash('sha256').update(html).digest('hex').slice(0, 12)}`;
const etag = `\"${etagToken}\"`;
const rows = [];
for (let offset = 0; offset < compressed.length; offset += 16) {
  rows.push(`  ${Array.from(compressed.subarray(offset, offset + 16),
    value => `0x${value.toString(16).padStart(2, '0')}`).join(', ')},`);
}

const output = `// Generated by tools/generate-web-assets.mjs. Do not edit manually.\n` +
  `#pragma once\n\n#include <cstddef>\n#include <cstdint>\n\n` +
  `#if __has_include(<Arduino.h>)\n#include <Arduino.h>\n#else\n#ifndef PROGMEM\n#define PROGMEM\n#endif\n#endif\n\n` +
  `namespace gridopoly::server {\n\n` +
  `static const std::uint8_t kWebUiGzip[] PROGMEM = {\n${rows.join('\n')}\n};\n` +
  `static constexpr std::size_t kWebUiGzipSize = sizeof(kWebUiGzip);\n\n` +
  `static constexpr char kWebUiEtag[] = "${etag.replaceAll('"', '\\"')}";\n\n` +
  `static constexpr char kWebUiEtagToken[] = "${etagToken}";\n\n` +
  `}  // namespace gridopoly::server\n`;

fs.writeFileSync(outputUrl, output);
console.log(`GRIDOPOLY_WEB_ASSET_OK html=${html.length} gzip=${compressed.length} tiles=${tileAssetNames.length}`);
